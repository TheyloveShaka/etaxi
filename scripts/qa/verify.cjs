const path = require('path')
const { chromium } = require('C:/Users/DELL/Desktop/projects/Money makers/frozen-basket/node_modules/playwright')
const url = process.argv[2] || 'http://localhost:4312'
const out = path.join(__dirname, '..', '..', 'docs', 'shots')
;(async () => {
  const b = await chromium.launch()
  const errs = []
  const c = await b.newContext({ viewport: { width: 1440, height: 900 } })
  const p = await c.newPage(); p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()) })
  await p.goto(url, { waitUntil: 'networkidle' }); await p.waitForTimeout(2500)
  const r = {}
  r.heroInertAtTop = await p.evaluate(() => document.querySelector('[data-hero-copy]').inert)
  const max = await p.evaluate(() => document.documentElement.scrollHeight - innerHeight)
  await p.evaluate(y => scrollTo(0, y), Math.round(max * 0.62)); await p.waitForTimeout(1000)
  r.heroInertMid = await p.evaluate(() => document.querySelector('[data-hero-copy]').inert)
  await p.keyboard.press('Tab'); await p.keyboard.press('Tab'); await p.keyboard.press('Tab'); await p.keyboard.press('Tab'); await p.keyboard.press('Tab')
  r.focusAfter5Tabs = await p.evaluate(() => { const e = document.activeElement; const q = e.getBoundingClientRect(); return [e.tagName, (e.textContent || '').trim().slice(0, 20), Math.round(q.left), Math.round(q.top)] })
  r.signs = await p.evaluate(() => [...document.querySelectorAll('[data-sign]')].map(s => { const q = s.getBoundingClientRect(); return [s.textContent.trim(), Math.round(q.left), Math.round(q.right)] }))
  r.roadRight = await p.evaluate(() => Math.round(innerWidth / 2 + Math.min(190, Math.max(120, innerWidth * 0.12)) / 2))
  await p.screenshot({ path: path.join(out, 'vfy-sign.png') })
  await p.evaluate(() => scrollTo(0, 0)); await p.waitForTimeout(900)
  r.heroInertBack = await p.evaluate(() => document.querySelector('[data-hero-copy]').inert)
  await p.click('a[href="#end"]'); await p.waitForTimeout(1800)
  r.skip = await p.evaluate(() => ({ atBottom: Math.abs(scrollY - (document.documentElement.scrollHeight - innerHeight)) < 400, year: document.querySelector('[data-year]').textContent }))
  r.icons = await p.evaluate(async () => Object.fromEntries(await Promise.all(['/favicon.ico', '/apple-touch-icon.png', '/site.webmanifest', '/404.html'].map(async u => [u, (await fetch(u)).status]))))
  await p.goto(url + '/404.html', { waitUntil: 'networkidle' }); await p.waitForTimeout(800)
  r.nf = await p.evaluate(() => ({ h1: document.querySelector('h1')?.textContent, font: getComputedStyle(document.querySelector('h1')).fontFamily.split(',')[0] }))
  await p.screenshot({ path: path.join(out, 'vfy-404.png') })
  const s = await b.newContext({ viewport: { width: 1280, height: 720 } }); const q = await s.newPage()
  await q.goto(url, { waitUntil: 'networkidle' }); await q.waitForTimeout(2500)
  r.facts720 = await q.evaluate(() => Math.round(Math.max(...[...document.querySelectorAll('.fact')].map(f => f.getBoundingClientRect().bottom))))
  r.errors = errs
  console.log(JSON.stringify(r))
  await b.close()
})()
